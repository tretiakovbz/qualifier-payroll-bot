/** Индекс фразы, отличный от предыдущего */
export function pickIndex(length: number, previous: number, random = Math.random): number {
  if (length <= 1) return 0;
  let i = Math.floor(random() * (length - 1));
  if (i >= previous && previous >= 0 && previous < length) i += 1;
  return i;
}
